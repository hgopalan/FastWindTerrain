# A case with no inputs file at all
# ---------------------------------------------------------------------------

@pytest.mark.slow
def test_python_only_case_matches_the_inputs_file(amrex, terrain_points,
                                                  run_exe, Plotfile, tmp_path):
    """Grid, terrain point cloud and profile, all from Python, against the
    executable's plotfile for the same case.

    The session's AMReX was initialized with NO arguments, so ParmParse
    holds nothing: every value here has to have come from the dicts.
    """
    inputs = write_inputs(tmp_path / "inputs_ref",
                          ["grid.output_format = both",
                           "output.format = plt",
                           "grid.plot_file = plt_ref",
                           "grid.report_file = grid_report_ref.txt"])
    run_exe(inputs)

    g = fwt.Grid(GRID)
    t = fwt.Terrain(g, {"points": terrain_points})
    inf = fwt.Inflow(g, t, INFLOW)

    pf = Plotfile(str(tmp_path / "plt_ref"))
    # u0/v0/w0 are the field before any correction -- which is what a
    # standalone Inflow produces, and why write_inputs turns the surface
    # condition off.
    pairs = [("u0", inf.velocity[0]), ("v0", inf.velocity[1]),
             ("w0", inf.velocity[2]), ("mask", t.mask),
             ("terrain_z", t.z_terrain)]

    compared = 0
    for pfname, arr in pairs:
        f = pf.field(pfname)
        for k in range(NZ):
            for j in range(0, NY, 4):
                for i in range(0, NX, 4):
                    assert float(arr[k, j, i]) == float(f(i, j, k)), (
                        f"{pfname} at ({i},{j},{k}) differs between the "
                        f"Python-built case and the inputs file. The point "
                        f"cloud goes through the same interpolation, so this "
                        f"means there are two code paths.")
                    compared += 1
    assert compared > 2000
    assert t.n_points > 0 and t.n_solid > 0


