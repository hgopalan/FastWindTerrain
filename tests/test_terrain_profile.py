"""
Terrain and inflow built from Python, with no file anywhere
(was regtests/phase12_terrain_profile_python).

The terrain arrives as a numpy ``(n, 3)`` point cloud and the inflow as
two ``(n, 3)`` arrays, bypassing the CSV and text readers entirely. The
demand is that this changes nothing: a case described only in Python must
reproduce the file-driven case BIT FOR BIT. Not close -- the point cloud
goes through the same inverse-distance interpolation, so any difference
would mean there are two code paths where there should be one.

Deliberately no anisotropy and no O'Brien in the reference case: both run
inside Solver::Setup and rewrite the velocity, so the plotfile's ``u0``
would no longer be the profile a standalone Inflow produces. The
comparison has to be between the same two things.
"""

import numpy as np
import pytest

import fastwindterrain as fwt
from conftest import REPO, TERRAIN_CSV

PROFILE_TXT = REPO / "regtests" / "phase4_bc_direction" / "user_profile.txt"

NX, NY, NZ = 24, 24, 40
GRID = {
    "n_cell": (NX, NY, NZ),
    "prob_lo": (0.0, 0.0, 0.0),
    "prob_hi": (1000.0, 1000.0, 483.19909696997223),
    "dz0": 4.0,
    "stretching_ratio": 1.05,
    "max_grid_size": 16,
}
INFLOW = {
    "mode": "powerlaw",
    "u_ref": 8.0,
    "v_ref": 6.0,
    "z_ref": 10.0,
    "powerlaw_exponent": 0.14,
    "z0": 0.1,
}


@pytest.fixture(scope="session")
def profile_table():
    """The six-column user profile, as one ``(n, 6)`` array."""
    if not PROFILE_TXT.is_file():                       # pragma: no cover
        pytest.skip(f"profile data not found at {PROFILE_TXT}")
    return np.loadtxt(PROFILE_TXT, delimiter=",", comments="#", skiprows=6)


def write_inputs(path, extra=()):
    """The same case as GRID/INFLOW, as an inputs file."""
    lines = ["# generated by tests/test_terrain_profile.py",
             f"grid.n_cell  = {' '.join(str(v) for v in GRID['n_cell'])}",
             f"grid.prob_lo = {' '.join(repr(v) for v in GRID['prob_lo'])}",
             f"grid.prob_hi = {' '.join(repr(v) for v in GRID['prob_hi'])}",
             f"grid.dz0 = {GRID['dz0']!r}",
             f"grid.stretching_ratio = {GRID['stretching_ratio']!r}",
             f"grid.max_grid_size = {GRID['max_grid_size']}",
             f"terrain.file = {TERRAIN_CSV}"]
    for k, v in INFLOW.items():
        # repr() would quote a string, and ParmParse takes the quotes
        # literally -- "'powerlaw'" is not a mode.
        lines.append(f"inflow.{k} = {v if isinstance(v, str) else repr(v)}")
    lines.append("poisson.n_projections = 1")
    # u0 in the output is copied AFTER the surface condition and O'Brien
    # (Solver.cpp), so it is not the raw profile unless both are off. These
    # tests compare a standalone Inflow against it, and their subject is
    # that the point cloud and the profile go through one code path -- the
    # surface condition is phase10_surface_condition's business.
    lines.append("surface.type = none")
    lines.extend(extra)
    path.write_text("\n".join(lines) + "\n")
    return path


