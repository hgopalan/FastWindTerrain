def _bad_terrains(g, pts, tab):
    return {
        # Two sources of truth: picking a winner would be worse than
        # refusing.
        "points and file together": lambda: fwt.Terrain(
            g, {"points": pts, "file": str(TERRAIN_CSV)}),
        "unknown key": lambda: fwt.Terrain(g, {"flat_elevaton": 0.0}),
        "flattened points": lambda: fwt.Terrain(
            g, {"points": pts.reshape(-1)}),
        "six-column points": lambda: fwt.Terrain(g, {"points": tab}),
        "no points at all": lambda: fwt.Terrain(g, {"points": pts[:0]}),
        "zero neighbours": lambda: fwt.Terrain(
            g, {"points": pts, "idw_n_neighbors": 0}),
        "missing file": lambda: fwt.Terrain(g, {"file": "no_such.csv"}),
    }


def _bad_inflows(g, t, tab):
    return {
        "calm reference wind": lambda: fwt.Inflow(
            g, t, {"u_ref": 0.0, "v_ref": 0.0}),
        "unknown mode": lambda: fwt.Inflow(
            g, t, {"mode": "spline", "u_ref": 1.0}),
        "table in the wrong mode": lambda: fwt.Inflow(
            g, t, {"mode": "powerlaw", "u_ref": 1.0,
                   "points": tab[:, 0:3], "velocity": tab[:, 3:6]}),
        "points without velocity": lambda: fwt.Inflow(
            g, t, {"mode": "userfile", "points": tab[:, 0:3]}),
        "userfile with nothing": lambda: fwt.Inflow(
            g, t, {"mode": "userfile"}),
        "table and file together": lambda: fwt.Inflow(
            g, t, {"mode": "userfile", "file": str(PROFILE_TXT),
                   "points": tab[:, 0:3], "velocity": tab[:, 3:6]}),
    }


def test_bad_terrain_and_inflow_raise(amrex, terrain_points, profile_table):
    """Ambiguous or malformed input raises rather than picking a winner
    or being quietly reshaped -- and the interpreter survives all of it,
    which is the point of raising instead of aborting."""
    g = fwt.Grid(GRID)
    t = fwt.Terrain(g, {"flat_elevation": 0.0})

    cases = {}
    cases.update(_bad_terrains(g, terrain_points, profile_table))
    cases.update(_bad_inflows(g, t, profile_table))

    for label, build in cases.items():
        with pytest.raises((ValueError, TypeError)):
            build()

    assert float(fwt.Inflow(g, t, {"u_ref": 3.0, "v_ref": 4.0}).speed_ref) == 5.0
