def test_numpy_points_match_the_csv(amrex, terrain_points):
    g = fwt.Grid(GRID)
    a = fwt.Terrain(g, {"points": terrain_points})
    b = fwt.Terrain(g, {"file": str(TERRAIN_CSV)})

    assert a.n_points == b.n_points > 0
    assert np.array_equal(a.z_terrain, b.z_terrain)
    assert np.array_equal(a.mask, b.mask)
    assert a.z_min == b.z_min
    assert a.z_max == b.z_max
    # The interpolation is not the identity -- if it were, the equalities
    # above would pass for the wrong reason.
    assert float(a.z_terrain.max() - a.z_terrain.min()) > 1.0


def test_numpy_velocity_table_matches_the_file(amrex, profile_table):
    g = fwt.Grid(GRID)
    t = fwt.Terrain(g, {"flat_elevation": 0.0})
    a = fwt.Inflow(g, t, {"mode": "userfile",
                          "points": profile_table[:, 0:3],
                          "velocity": profile_table[:, 3:6]})
    b = fwt.Inflow(g, t, {"mode": "userfile", "file": str(PROFILE_TXT)})

    assert a.n_points == b.n_points > 0
    assert np.array_equal(a.velocity, b.velocity)
    assert a.flux_in == b.flux_in
    assert a.flux_out == b.flux_out
    assert float(np.abs(a.velocity).max()) > 0.0, "the field is all zero"


