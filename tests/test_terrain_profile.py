# No ParmParse leak
# ---------------------------------------------------------------------------

def test_terrain_and_inflow_ignore_parmparse(run_py, tmp_path):
    """``terrain.file`` is the leak that would hurt most: inheriting it
    silently swaps the terrain under a whole dataset, and every field
    still looks perfectly reasonable.

    Out of process because it needs AMReX initialized from a file.
    """
    inputs = write_inputs(tmp_path / "inputs_leak")
    r = run_py(f"""
import numpy as np
import fastwindterrain as fwt
fwt.initialize([{str(inputs)!r}])
g = fwt.Grid({GRID!r})

# The inputs file names a 100 m hill. Omitting it here must give flat
# ground, not that hill.
t = fwt.Terrain(g, {{}})
print("::NPOINTS", t.n_points)
print("::NSOLID", t.n_solid)
print("::ZMAX", repr(float(t.z_max)))

# Likewise the profile: the file sets u_ref/v_ref, but a dict that names
# its own must use its own.
inf = fwt.Inflow(g, t, {{"mode": "powerlaw", "u_ref": 1.0, "v_ref": 0.0}})
print("::SPEED", repr(float(inf.speed_ref)))
print("::AT100", repr(float(inf.profile_speed(100.0))))
fwt.finalize()
""")

    assert int(r["NPOINTS"]) == 0, (
        "the dict omitted both terrain points and terrain.file, so the "
        "ground must be flat -- the inputs file's terrain leaked through "
        "ParmParse")
    assert int(r["NSOLID"]) == 0
    assert float(r["ZMAX"]) == 0.0
    assert float(r["SPEED"]) == 1.0, (
        "speed_ref should come from the dict, not from the inputs file")
    # The dict does not set z_ref, so the default 10 m has to be used
    # rather than the file's: 1.0 * (100/10)^0.14.
    assert float(r["AT100"]) == pytest.approx(
        1.0 * (100.0 / 10.0) ** 0.14, abs=1e-12)


