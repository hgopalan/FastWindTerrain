def test_the_extension_module_sits_inside_the_package():
    """Both build paths must agree about this: the in-tree layout under
    build/python and the wheel's are the same package, or an import that
    works in one fails in the other."""
    assert fwt._fastwindterrain.__name__ == "fastwindterrain._fastwindterrain"


def test_dataset_is_importable_as_a_submodule():
    from fastwindterrain import dataset
    assert dataset.FIELDS
    assert fwt.dataset is dataset


def test_every_public_name_has_a_docstring():
    """These are the bindings' documentation -- there is no separate API
    reference to fall back on."""
    missing = [n for n in fwt.__all__
               if not (getattr(fwt, n).__doc__ or "").strip()
               and n not in ("__version__",)]
    assert missing == [], f"undocumented public names: {missing}"


def test_dataset_functions_are_documented():
    from fastwindterrain import dataset
    missing = [n for n in dataset.__all__
               if not (getattr(dataset, n).__doc__ or "").strip()]
    assert missing == [], f"undocumented dataset names: {missing}"
