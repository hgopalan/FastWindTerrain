#!/usr/bin/env python3
"""
build_corpus.py -- survey the reference fires, then split them safely.

Two stages, deliberately separate:

    python3 cases/build_corpus.py --survey          # needs network + geo stack
    python3 cases/build_corpus.py --split           # offline, pure arithmetic

The survey downloads one wide SRTM tile per fire, cuts it into a 3 x 3 grid
of overlapping 5 km windows, screens the site, and writes a small
corpus/<slug>/survey.json holding everything the split needs -- per-window
extremes and terrain descriptors. That file is committed; the tile it came
from (about ten megabytes) is not.

The split reads those surveys and nothing else. So the manifest can be
regenerated, reviewed and tested on a machine with no network, no geo stack
and no tiles, which is what makes the split reproducible rather than
something that happened once on a laptop.

    python3 cases/build_corpus.py --summary         # what the manifest says
    python3 cases/build_corpus.py --survey --only creek_fire --force
"""

import argparse
import json
import os
import sys
import time

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
if HERE not in sys.path:
    sys.path.insert(0, HERE)

import casegen                                              # noqa: E402
import corpus                                               # noqa: E402

HEADER = ("Generated by cases/build_corpus.py from wildfires_reference.csv; "
          "do not edit by hand.")


# ---------------------------------------------------------------------------
# Stage 1: survey
# ---------------------------------------------------------------------------

def survey_site(case, subsample=1, keep_tile=True):
    """Download one site's tile, cut its windows, and describe each of them.

    Everything expensive happens here, once per site. What comes out is a
    few kilobytes that the split stage can work from forever.
    """
    import numpy as np

    folder = corpus.site_dir(case.slug)
    if not os.path.isdir(folder):
        os.makedirs(folder)

    points = case.download_points(subsample=subsample,
                                  half_width=corpus.CORPUS_HALF_WIDTH_M,
                                  extent=corpus.CORPUS_EXTENT_M)
    z = points[:, 2]
    if float(z.max() - z.min()) <= 0.0:
        raise RuntimeError(
            f"{case.slug}: the downloaded tile is perfectly flat (every "
            f"point at {z[0]:.1f} m). Real ground is not, so this is "
            f"missing or nodata elevation data. Nothing has been written.")

    survey = {
        "slug": case.slug,
        "name": case.name,
        "state": case.state,
        "year": case.year,
        "lat": case.lat,
        "lon": case.lon,
        "n_points": int(z.size),
        "subsample": int(subsample),
        "z_min": float(z.min()),
        "z_max": float(z.max()),
        "z_mean": float(z.mean()),
        "relief": float(z.max() - z.min()),
        "sea_fraction": float(np.mean(z <= 0.0)),
        "extent_m": corpus.CORPUS_EXTENT_M,
        "half_width_m": corpus.CORPUS_HALF_WIDTH_M,
        "window_m": corpus.WINDOW_M,
        "stride_m": corpus.WINDOW_STRIDE_M,
        "n_windows_per_side": corpus.N_WINDOWS_PER_SIDE,
        "source": "SRTM1 via cases/srtm_terrain_reader.py",
        "note": HEADER,
    }

    windows = []
    for iw, jw, x0, y0 in corpus.window_offsets():
        wp = corpus.window_points(points, x0, y0)
        zg = corpus.grid_terrain(wp)
        entry = {
            "id": corpus.window_id(case.slug, iw, jw),
            "site": case.slug,
            "i": iw, "j": jw,
            "x0": float(x0), "y0": float(y0),
            "n_points": int(wp.shape[0]),
            # From the point cloud including the halo, which is what the
            # solver's IDW sees and therefore what has to fit in the domain.
            "z_min": float(wp[:, 2].min()),
            "z_max": float(wp[:, 2].max()),
        }
        entry.update(corpus.descriptors(zg))
        # The grid this window would get, recorded now so the split stage
        # never needs the tile back.
        grid = casegen.grid_from_relief(entry["z_min"], entry["z_max"])
        entry["prob_lo_z"] = grid["prob_lo"][2]
        entry["prob_hi_z"] = grid["prob_hi"][2]
        entry["stretching_ratio"] = grid["stretching_ratio"]
        casegen.assert_fits(wp[:, 2], grid["prob_lo"][2], grid["prob_hi"][2],
                            what=f"{entry['id']} terrain")
        windows.append(entry)
    survey["windows"] = windows

    if keep_tile:
        casegen.write_terrain(corpus.tile_path(case.slug), points,
                              header_lines=[
            f"{case.name} ({case.state} {case.year}) at "
            f"{case.lat:.4f}, {case.lon:.4f}",
            f"corpus tile: {corpus.CORPUS_EXTENT_M:.0f} m square plus "
            f"{casegen.HALO_M:.0f} m halo, {corpus.N_WINDOWS_PER_SIDE}x"
            f"{corpus.N_WINDOWS_PER_SIDE} windows of "
            f"{corpus.WINDOW_M:.0f} m at a {corpus.WINDOW_STRIDE_M:.0f} m "
            f"stride",
        ])
    with open(corpus.site_survey_path(case.slug), "w") as f:
        json.dump(survey, f, indent=2, sort_keys=True)
        f.write("\n")
    return survey


def run_survey(args):
    cases = corpus.candidate_sites()
    if args.only:
        wanted = set(args.only)
        cases = [c for c in cases if c.slug in wanted]
        unknown = wanted - {c.slug for c in cases}
        if unknown:
            print(f"no such site: {sorted(unknown)}", file=sys.stderr)
            return 2

    done = failed = skipped = 0
    for n, case in enumerate(cases, 1):
        path = corpus.site_survey_path(case.slug)
        if os.path.isfile(path) and not args.force:
            print(f"[{n:2d}/{len(cases)}] {case.slug:32s} already surveyed")
            skipped += 1
            continue
        t0 = time.time()
        print(f"[{n:2d}/{len(cases)}] {case.slug:32s} ", end="", flush=True)
        try:
            survey = survey_site(case, subsample=args.subsample,
                                 keep_tile=not args.no_tile)
        except Exception as exc:
            # One bad tile must not lose the other twenty-eight surveys.
            print(f"FAILED: {type(exc).__name__}: "
                  f"{str(exc).splitlines()[0][:120]}")
            failed += 1
            continue
        # Screening is the split stage's job; reported here only so a long
        # survey run says what it is collecting.
        ok, reason, kept = corpus.screen_site(survey)
        flag = "" if ok else f"  would be REJECTED: {reason}"
        print(f"{survey['relief']:7.0f} m relief, "
              f"{survey['n_points']:7d} pts, {len(kept)} windows, "
              f"{time.time() - t0:5.1f} s{flag}")
        done += 1

    print(f"\nsurveyed {done}, skipped {skipped}, failed {failed}")
    return 1 if failed else 0


