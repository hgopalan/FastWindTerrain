def write(path, text, executable=False):
    with open(path, "w") as f:
        f.write(text)
    if executable:
        os.chmod(path, 0o755)
    return path


def build(case):
    if not os.path.isdir(case.folder):
        os.makedirs(case.folder)

    write(os.path.join(case.folder, "prepare.py"),
          PREPARE_TEMPLATE.format(generated=GENERATED, name=case.name,
                                  slug=case.slug), executable=True)
    write(os.path.join(case.folder, "run.py"),
          RUN_TEMPLATE.format(generated=GENERATED, name=case.name,
                              slug=case.slug), executable=True)
    write(os.path.join(case.folder, "README.md"),
          README_TEMPLATE.format(
              name=case.name, state=case.state, year=case.year,
              area_ha=case.area_ha, duration_days=case.duration_days,
              lat=case.lat, lon=case.lon,
              nx=casegen.N_CELL[0], ny=casegen.N_CELL[1], nz=casegen.N_CELL[2],
              why=WHY[case.slug]))

    meta = {
        "slug": case.slug, "name": case.name, "state": case.state,
        "year": case.year, "lat": case.lat, "lon": case.lon,
        "area_ha": case.area_ha, "duration_days": case.duration_days,
        "domain_m": casegen.DOMAIN_M,
        "n_cell": list(casegen.N_CELL),
        "download_bbox_deg": case.bbox_deg(),
        "note": ("Generated by cases/build_catalogue.py from "
                 "wildfires_reference.csv; the grid lives in survey.json, "
                 "which prepare.py writes."),
    }
    with open(os.path.join(case.folder, casegen.CASE_FILE), "w") as f:
        json.dump(meta, f, indent=2, sort_keys=True)
        f.write("\n")

    return case.folder


def check_upstream():
    """Have the vendored files changed upstream? Network, on request only."""
    try:
        from urllib.request import urlopen
    except ImportError:                                  # pragma: no cover
        print("no urllib available", file=sys.stderr)
        return 1

    drifted = []
    for name, meta in sorted(UPSTREAM.items()):
        local = os.path.join(HERE, name)
        have = hashlib.sha256(open(local, "rb").read()).hexdigest()
        if have != meta["sha256"]:
            print(f"[LOCAL] {name} differs from the vendored revision "
                  f"({have[:12]} vs {meta['sha256'][:12]}) -- it was edited "
                  f"here")
            drifted.append(name)
            continue
        try:
            remote = hashlib.sha256(urlopen(meta["url"], timeout=30).read()) \
                .hexdigest()
        except Exception as e:                           # pragma: no cover
            print(f"[SKIP]  {name}: could not fetch upstream ({e})")
            continue
        if remote == have:
            print(f"[OK]    {name} matches upstream")
        else:
            print(f"[DRIFT] {name} has changed upstream "
                  f"({have[:12]} here, {remote[:12]} there). Re-vendor it and "
                  f"update UPSTREAM in this file if the change is wanted.")
            drifted.append(name)
    return 1 if drifted else 0


def main():
    p = argparse.ArgumentParser(
        description="(Re)generate the case folders from the reference CSV.")
    p.add_argument("--list", action="store_true",
                   help="show the catalogue and exit")
    p.add_argument("--check-upstream", action="store_true",
                   help="diff the vendored files against wildfire_levelset")
    args = p.parse_args()

    if args.check_upstream:
        return check_upstream()

    cases = casegen.catalogue()
    if args.list:
        for c in cases:
            print(f"{c.slug:22s} {c.state:12s} {c.year}  "
                  f"{c.lat:8.4f} {c.lon:10.4f}  {WHY[c.slug]}")
        return 0

    for c in cases:
        print(f"wrote {os.path.relpath(build(c), os.path.dirname(HERE))}/")
    print(f"\n{len(cases)} case folders. Each needs its terrain downloading:")
    print(f"    python3 cases/{cases[0].slug}/prepare.py")
    return 0


if __name__ == "__main__":
    sys.exit(main())
