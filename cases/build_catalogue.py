#!/usr/bin/env python3
"""
build_catalogue.py -- (re)generate the case folders from the reference CSV.

One folder per fire, each holding a prepare.py that downloads its terrain
and a run.py that solves it. The scripts are generated rather than
hand-written because there are eight of them and one implementation, in
casegen.py; regenerating is how a change to that implementation reaches
every case at once.

Nothing here touches the network, and nothing overwrites a survey.json or a
terrain file -- only the scripts, the README and case.json are (re)written.

Usage:
    python3 cases/build_catalogue.py                 # write the folders
    python3 cases/build_catalogue.py --list          # just show the set
    python3 cases/build_catalogue.py --check-upstream

--check-upstream fetches the two vendored files from wildfire_levelset and
reports whether our copies still match. It is the only thing in this
directory that needs a network, and it is never run automatically.
"""

